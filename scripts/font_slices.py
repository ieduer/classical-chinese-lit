#!/usr/bin/env python3
"""Split one large CJK web font into unicode-range slices (portal-design-pass-20261026).

The browser downloads only the slices whose characters are on screen, so the full glyph
set stays available while a page typically fetches a few hundred KB instead of the whole
font. Slice order: basic Latin/punctuation, then the site's own characters by frequency,
then every remaining glyph of the font in code point order. Hinting is dropped (web
rendering ignores it on most screens); layout features (GSUB/GPOS) are kept.

usage: font_slices.py <font> <family> <url-prefix> <out-dir> <corpus-file>...
writes <out-dir>/<family>.<n>.<hash>.woff2 and <out-dir>/<family>.css, prints a JSON summary.
"""
import hashlib, io, json, os, sys, collections
from concurrent.futures import ProcessPoolExecutor
from fontTools.ttLib import TTFont
from fontTools import subset

FIRST = 0x20, 0x7E
SITE_SLICE = 120
REST_SLICE = 400

def ranges(cps):
    cps = sorted(cps); out = []; start = prev = cps[0]
    for cp in cps[1:]:
        if cp == prev + 1: prev = cp; continue
        out.append((start, prev)); start = prev = cp
    out.append((start, prev))
    return ', '.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in out)

def build_slice(raw, group):
    opts = subset.Options(); opts.flavor = 'woff2'; opts.hinting = False; opts.layout_features = ['*']; opts.name_IDs = ['*']; opts.notdef_outline = True
    font = TTFont(io.BytesIO(raw)); sub = subset.Subsetter(options=opts); sub.populate(unicodes=group); sub.subset(font)
    buf = io.BytesIO(); font.flavor = 'woff2'; font.save(buf)
    return buf.getvalue()

def main():
    source_path, family, prefix, out_dir = sys.argv[1:5]
    corpus = sys.argv[5:]
    # Decode the (usually WOFF2) source once; every slice then loads the plain TTF bytes.
    source = TTFont(source_path); source.flavor = None
    raw = io.BytesIO(); source.save(raw); raw = raw.getvalue()
    cmap = set(source.getBestCmap())
    freq = collections.Counter()
    for path in corpus:
        with open(path, encoding='utf-8', errors='ignore') as fh:
            freq.update(ord(ch) for ch in fh.read())
    basic = sorted(cp for cp in cmap if FIRST[0] <= cp <= FIRST[1] or cp in (0x3000, 0x3001, 0x3002, 0xFF0C, 0xFF1A, 0xFF1B, 0xFF01, 0xFF1F, 0x201C, 0x201D, 0x2018, 0x2019, 0x300A, 0x300B, 0x3008, 0x3009, 0x2014, 0x2026, 0xB7))
    used = [cp for cp, _ in freq.most_common() if cp in cmap and cp not in basic]
    rest = sorted(cmap - set(basic) - set(used))
    groups = [basic] + [used[i:i + SITE_SLICE] for i in range(0, len(used), SITE_SLICE)] + [rest[i:i + REST_SLICE] for i in range(0, len(rest), REST_SLICE)]
    os.makedirs(out_dir, exist_ok=True)
    css, files, total = [], [], 0
    groups = [g for g in groups if g]
    with ProcessPoolExecutor(max_workers=min(6, os.cpu_count() or 2)) as pool:
        blobs = list(pool.map(build_slice, [raw] * len(groups), groups))
    site_count = (len(used) + SITE_SLICE - 1) // SITE_SLICE
    for n, (group, data) in enumerate(zip(groups, blobs)):
        name = f'{family}.{n:02d}.{hashlib.sha256(data).hexdigest()[:10]}.woff2'
        with open(os.path.join(out_dir, name), 'wb') as fh: fh.write(data)
        total += len(data); files.append({'file': name, 'bytes': len(data), 'codepoints': len(group), 'site': 0 < n <= site_count})
        css.append(f"@font-face {{\n  font-family: \"{family}\";\n  src: url(\"{prefix}{name}\") format(\"woff2\");\n  font-display: swap;\n  unicode-range: {ranges(group)};\n}}")
    with open(os.path.join(out_dir, f'{family}.css'), 'w', encoding='utf-8') as fh:
        fh.write(f'/* Generated by font_slices.py from {os.path.basename(source_path)}: {len(files)} unicode-range slices, browser loads only those on screen. */\n' + '\n'.join(css) + '\n')
    print(json.dumps({'source_bytes': os.path.getsize(source_path), 'codepoints': len(cmap), 'site_codepoints': len(used), 'slices': len(files), 'total_bytes': total,
                      'site_slices_bytes': sum(f['bytes'] for f in files if f['site']) + files[0]['bytes'], 'largest': max(f['bytes'] for f in files)}))

if __name__ == '__main__':
    main()
